-- APPLICATION CONTRACT (not enforced solely by the DDL above):
-- 1. Every inventory write/expiry worker uses a separate DB session per task.
--    Lock performance -> affected member quotas by user_id -> holds by id ->
--    orders by id -> seats by id. One transaction processes one performance.
-- 2. After acquiring all locks, read SELECT clock_timestamp() AS decision_at.
--    Do not use now()/CURRENT_TIMESTAMP for expiry decisions after lock waits:
--    they represent transaction-start time. decision_at < expires_at is valid;
--    equality is expired. This locked final validation is the linearization point,
--    not HTTP arrival and not commit time. Any DB error still rolls back the TX.
-- 3. Create expiry as min(decision_at + configured TTL, sales close, show start).
--    TTL=180s is a team-review default, pending team review.
-- 4. Clean expired ACTIVE groups before computing active+held+requested <=
--    performances.max_tickets_per_user. Expiry is not an automatic DB event.
-- 5. Counters equal CONFIRMED order quantities and unclosed hold quantities.
--    Hold/item count, hold/item/current-pointer ownership, price sums, all
--    item/order/payment/ticket transitions must be updated in the same TX.
-- 6. Claim: hold ACTIVE + immutable item snapshots -> seats HELD/current_hold_id
--    -> held counter increases -> COMMIT. Human payment waits outside this TX.
-- 7. Confirm: validate owner/session, policy, ACTIVE/unexpired and all current
--    pointers before local mock approval. On success: hold CONSUMED, seats
--    RESERVED/pointer NULL, held decreases, active increases; order, items,
--    PAID payment, ISSUED tickets commit together. No network PG call in this TX.
-- 8. Idempotency namespaces are separate: hold-create and reservation-confirm.
--    Each namespace is keyed by (authenticated user_id, request_key), across
--    all performances. Canonical confirm hash includes hold_id and all request
--    semantics; same key with different hash/hold is a conflict, never a replay.
--    An original confirmation key/hash can replay its original order, including
--    a later CANCELED order. A consumed hold cannot create another order.
--    Implementation default proposed for v4: a different confirmation key on an
--    already-consumed hold returns a conflict with the existing order reference;
--    the user can read that order separately. Do not silently reserve alias keys.
--    This strict original-key replay policy is a proposal for team review.
--    Cross-performance same-key races may reach UNIQUE; roll back then reread
--    the committed key/hash and classify conflict/replay. Never swallow errors.
-- 9. Release/expiry only transitions ACTIVE once and only clears a seat whose
--    current_hold_id equals that hold. Old A requests cannot release B's hold.
--    Do not double-decrement quota. Terminal holds never return to ACTIVE.
-- 10. Expected mock decline COMMITs RELEASED + seat/quota restoration before an
--     error response. Unexpected errors roll back, so an earlier ACTIVE hold
--     can remain and later be retried/released/expired. Cleanup plus expected
--     business refusal commits cleanup alone; throwing out of UoW would undo it.
-- 11. Whole-order cancellation restores active quota and seat availability,
--     records refund progress, and leaves the consumed hold as history.
-- 12. This coarse performance-row lock favors MVP correctness and serializes
--     brief same-performance writes. A/B/C or adding app servers does not remove
--     that bottleneck; throughput, pool wait and lock wait need later measurement.
-- 13. Keep hold/items immutable as history. No hard-delete cascades are defined.
--     Existing production orders need a separate hold_id migration strategy.
