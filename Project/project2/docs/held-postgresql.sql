-- AsyncTicket HELD v4: standalone PostgreSQL schema proposal, 2026-10-28.
-- 16 tables. Review before use; not an executed migration or database export.
-- HELD is a committed business state. Do not hold DB locks during payment screens.
-- TTL 180s, one ACTIVE hold/member/session, and whole-hold release are proposals.
-- Jinja2 integration adds no tables.

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    name VARCHAR(100) NOT NULL,
    phone_number VARCHAR(30),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Demand classification only; this table does not provision servers or lock seats.
CREATE TABLE traffic_profiles (
    code VARCHAR(1) PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    description TEXT NOT NULL,
    CHECK (code IN ('A','B','C'))
);

CREATE TABLE shows (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    description TEXT,
    performer VARCHAR(255),
    performance_type VARCHAR(50) NOT NULL,
    running_time_minutes INTEGER,
    poster_url TEXT,
    demand_tier VARCHAR(1) NOT NULL,
    tier_reason TEXT NOT NULL,
    tier_assessed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (running_time_minutes IS NULL OR running_time_minutes > 0),
    FOREIGN KEY (demand_tier) REFERENCES traffic_profiles (code)
);

CREATE TABLE venues (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    address VARCHAR(255) NOT NULL
);

CREATE TABLE stages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    UNIQUE (venue_id, name),
    FOREIGN KEY (venue_id) REFERENCES venues (id)
);

CREATE TABLE stage_seats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage_id BIGINT NOT NULL,
    section_name VARCHAR(50),
    seat_number VARCHAR(50) NOT NULL,
    UNIQUE (stage_id, seat_number),
    UNIQUE (id, stage_id),
    FOREIGN KEY (stage_id) REFERENCES stages (id)
);

CREATE TABLE performances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    show_id BIGINT NOT NULL,
    stage_id BIGINT NOT NULL,
    round_number INTEGER NOT NULL,
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    reservation_opens_at TIMESTAMPTZ NOT NULL,
    reservation_closes_at TIMESTAMPTZ NOT NULL,
    cancel_deadline_at TIMESTAMPTZ NOT NULL,
    max_tickets_per_user INTEGER NOT NULL DEFAULT 3,
    status VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED',
    UNIQUE (show_id, round_number),
    UNIQUE (id, stage_id),
    CHECK (round_number > 0),
    CHECK (max_tickets_per_user BETWEEN 1 AND 3),
    CHECK (starts_at < ends_at),
    CHECK (reservation_opens_at < reservation_closes_at AND reservation_closes_at <= starts_at),
    CHECK (cancel_deadline_at <= starts_at),
    CHECK (status IN ('SCHEDULED','OPEN','CLOSED','CANCELED')),
    FOREIGN KEY (show_id) REFERENCES shows (id),
    FOREIGN KEY (stage_id) REFERENCES stages (id)
);

CREATE TABLE performance_seats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    performance_id BIGINT NOT NULL,
    stage_id BIGINT NOT NULL,
    stage_seat_id BIGINT NOT NULL,
    seat_grade VARCHAR(30) NOT NULL,
    price NUMERIC(12,2) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE',
    current_hold_id BIGINT,
    UNIQUE (performance_id, stage_seat_id),
    UNIQUE (id, performance_id),
    FOREIGN KEY (performance_id, stage_id) REFERENCES performances (id, stage_id),
    FOREIGN KEY (stage_seat_id, stage_id) REFERENCES stage_seats (id, stage_id),
    CHECK (price >= 0),
    CHECK (status IN ('AVAILABLE','HELD','RESERVED','BLOCKED')),
    CONSTRAINT ck_seat_current_hold CHECK (
        (status = 'HELD' AND current_hold_id IS NOT NULL)
        OR (status IN ('AVAILABLE','RESERVED','BLOCKED') AND current_hold_id IS NULL)
    ),
    FOREIGN KEY (performance_id) REFERENCES performances (id),
    FOREIGN KEY (stage_seat_id) REFERENCES stage_seats (id)
);

CREATE TABLE member_performance_limits (
    user_id BIGINT NOT NULL,
    performance_id BIGINT NOT NULL,
    active_quantity INTEGER NOT NULL DEFAULT 0,
    held_quantity INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (user_id, performance_id),
    CHECK (active_quantity BETWEEN 0 AND 3),
    CHECK (held_quantity BETWEEN 0 AND 3),
    CONSTRAINT ck_member_total_quantity CHECK (active_quantity + held_quantity <= 3),
    FOREIGN KEY (user_id) REFERENCES users (id),
    FOREIGN KEY (performance_id) REFERENCES performances (id)
);

CREATE TABLE seat_holds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    performance_id BIGINT NOT NULL,
    request_key VARCHAR(100) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    quantity INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    expires_at TIMESTAMPTZ NOT NULL,
    closed_at TIMESTAMPTZ,
    close_reason VARCHAR(40),
    UNIQUE (user_id, request_key),
    UNIQUE (id, performance_id),
    UNIQUE (id, user_id, performance_id),
    CHECK (quantity BETWEEN 1 AND 3),
    CHECK (status IN ('ACTIVE','CONSUMED','RELEASED','EXPIRED')),
    CHECK (created_at < expires_at),
    CONSTRAINT ck_hold_closed_at CHECK (
        (status = 'ACTIVE' AND closed_at IS NULL)
        OR (status <> 'ACTIVE' AND closed_at IS NOT NULL)
    ),
    CHECK (closed_at IS NULL OR closed_at >= created_at),
    FOREIGN KEY (user_id) REFERENCES users (id),
    FOREIGN KEY (performance_id) REFERENCES performances (id)
);

CREATE TABLE seat_hold_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hold_id BIGINT NOT NULL,
    performance_id BIGINT NOT NULL,
    performance_seat_id BIGINT NOT NULL,
    price_at_hold NUMERIC(12,2) NOT NULL,
    UNIQUE (hold_id, performance_seat_id),
    -- Target key for a current pointer that must identify a member of this hold.
    UNIQUE (hold_id, performance_id, performance_seat_id),
    FOREIGN KEY (hold_id, performance_id) REFERENCES seat_holds (id, performance_id),
    FOREIGN KEY (performance_seat_id, performance_id) REFERENCES performance_seats (id, performance_id),
    CHECK (price_at_hold >= 0)
);

-- Added after both tables to resolve the intentional FK cycle.
-- Normal creation order in one TX: hold -> hold_items -> seat HELD/pointer.
-- MATCH SIMPLE means a NULL current_hold_id needs no current membership row.
ALTER TABLE performance_seats
    ADD CONSTRAINT fk_seat_current_hold_session
    FOREIGN KEY (current_hold_id, performance_id)
    REFERENCES seat_holds (id, performance_id);

ALTER TABLE performance_seats
    ADD CONSTRAINT fk_seat_current_hold_membership
    FOREIGN KEY (current_hold_id, performance_id, id)
    REFERENCES seat_hold_items (hold_id, performance_id, performance_seat_id);

CREATE TABLE reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(100) NOT NULL UNIQUE,
    user_id BIGINT NOT NULL,
    performance_id BIGINT NOT NULL,
    request_key VARCHAR(100) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    hold_id BIGINT NOT NULL UNIQUE,
    quantity INTEGER NOT NULL,
    total_amount NUMERIC(12,2) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'CONFIRMED',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    confirmed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    canceled_at TIMESTAMPTZ,
    UNIQUE (user_id, request_key),
    UNIQUE (id, performance_id),
    CHECK (quantity BETWEEN 1 AND 3),
    CHECK (total_amount >= 0),
    CHECK (status IN ('CONFIRMED','CANCELED')),
    CHECK ((status = 'CONFIRMED' AND canceled_at IS NULL) OR (status = 'CANCELED' AND canceled_at IS NOT NULL)),
    -- This also enforces that the order owner and session match its hold.
    FOREIGN KEY (hold_id, user_id, performance_id)
        REFERENCES seat_holds (id, user_id, performance_id),
    FOREIGN KEY (user_id) REFERENCES users (id),
    FOREIGN KEY (performance_id) REFERENCES performances (id)
);

CREATE TABLE reservation_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT NOT NULL,
    performance_id BIGINT NOT NULL,
    performance_seat_id BIGINT NOT NULL,
    price_at_reservation NUMERIC(12,2) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'CONFIRMED',
    UNIQUE (reservation_id, performance_seat_id),
    FOREIGN KEY (reservation_id, performance_id) REFERENCES reservations (id, performance_id),
    FOREIGN KEY (performance_seat_id, performance_id) REFERENCES performance_seats (id, performance_id),
    CHECK (price_at_reservation >= 0),
    CHECK (status IN ('CONFIRMED','CANCELED')),
    FOREIGN KEY (reservation_id) REFERENCES reservations (id),
    FOREIGN KEY (performance_seat_id) REFERENCES performance_seats (id)
);

CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT NOT NULL UNIQUE,
    transaction_reference VARCHAR(255) NOT NULL UNIQUE,
    method VARCHAR(20) NOT NULL DEFAULT 'MOCK',
    amount NUMERIC(12,2) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PAID',
    paid_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    refund_status VARCHAR(20) NOT NULL DEFAULT 'NONE',
    refunded_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
    refunded_at TIMESTAMPTZ,
    CHECK (amount >= 0 AND refunded_amount BETWEEN 0 AND amount),
    CHECK (method = 'MOCK'),
    CHECK (status IN ('PAID','REFUNDED')),
    CHECK (refund_status IN ('NONE','PENDING','COMPLETED','FAILED')),
    FOREIGN KEY (reservation_id) REFERENCES reservations (id)
);

CREATE TABLE tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_item_id BIGINT NOT NULL UNIQUE,
    ticket_code VARCHAR(100) NOT NULL UNIQUE,
    receive_method VARCHAR(20) NOT NULL DEFAULT 'ON_SITE',
    status VARCHAR(20) NOT NULL DEFAULT 'ISSUED',
    issued_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    canceled_at TIMESTAMPTZ,
    CHECK (status IN ('ISSUED','CANCELED')),
    CHECK (receive_method = 'ON_SITE'),
    FOREIGN KEY (reservation_item_id) REFERENCES reservation_items (id)
);

CREATE TABLE token_blacklist (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_jti VARCHAR(255) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uq_active_seat
    ON reservation_items (performance_seat_id) WHERE status = 'CONFIRMED';
CREATE UNIQUE INDEX uq_active_hold_member_session
    ON seat_holds (user_id, performance_id) WHERE status = 'ACTIVE';
CREATE INDEX ix_holds_expiry_active
    ON seat_holds (expires_at, performance_id) WHERE status = 'ACTIVE';
CREATE INDEX ix_hold_items_seat_history ON seat_hold_items (performance_seat_id);
CREATE INDEX ix_seats_current_hold ON performance_seats (current_hold_id)
    WHERE current_hold_id IS NOT NULL;
CREATE INDEX ix_reservations_member_session ON reservations (user_id, performance_id, status);
CREATE INDEX ix_seats_session_status ON performance_seats (performance_id, status);
CREATE INDEX ix_blacklist_expiry ON token_blacklist (expires_at);

